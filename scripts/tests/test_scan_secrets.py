"""Secret_Scan tests — scripts/scan-secrets.sh driven through subprocess.

The scan takes its scope from ``git ls-files``, so every fixture here is a real
throwaway git repository: ``git init`` plus ``git add``. Anything the fixture
does not stage is out of scope by construction, which is the property the design
relies on for node_modules/, cdk.out/ and config/accounts.json.

No 12-digit literal appears in this source. Identifiers are assembled at runtime
by ``fake_account_id`` / ``placeholder_id`` from conftest (Requirement 6.5).

Requirements: 6.5, 6.6
"""

from __future__ import annotations

import hashlib
import shutil
import subprocess
from pathlib import Path

import pytest

from .conftest import REPO_ROOT, fake_account_id, placeholder_id

SCAN_SCRIPT = REPO_ROOT / "scripts" / "scan-secrets.sh"
BASELINE_NAME = "scripts/scan-secrets.baseline"
BASH = shutil.which("bash") or "/bin/bash"
GIT = shutil.which("git") or "/usr/bin/git"

# A CloudFormation-generated physical name, assembled at runtime from its parts
# so the committed source carries no live-looking name either: stack, logical id
# plus 8-hex logical-id hash, and the random suffix.
CFN_STACK = "DevSampleStack"
CFN_LOGICAL = "QueueResourcessqssample"
CFN_HASH = "AB12CD34"
CFN_SUFFIX = "Zq7XmT4vB2ke"
CFN_NAME = f"{CFN_STACK}-{CFN_LOGICAL}{CFN_HASH}-{CFN_SUFFIX}"


def baseline(*entries: tuple[str, str]) -> str:
    """Render a baseline file body from (path glob, accepted value) pairs.

    The digest is computed here the same way the script and the baseline's own
    instructions compute it: sha256 of the exact value with no trailing newline.
    """
    lines = ["# generated by the test suite"]
    for path, value in entries:
        digest = hashlib.sha256(value.encode()).hexdigest()
        lines.append(f"{path} | {digest} | accepted by a test")
    return "\n".join(lines) + "\n"


def make_git_repo(root: Path, files: dict[str, str], stage: bool = True) -> Path:
    """Create a git repo at ``root`` holding ``files``, staging them by default.

    The scan resolves the repository root from its own location, so the script is
    copied to ``<root>/scripts/scan-secrets.sh`` exactly as it sits in this
    repository.
    """
    root.mkdir(parents=True, exist_ok=True)
    (root / "scripts").mkdir(exist_ok=True)
    shutil.copy2(SCAN_SCRIPT, root / "scripts" / "scan-secrets.sh")

    for relative, content in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            target.write_bytes(content)
        else:
            target.write_text(content)

    subprocess.run([GIT, "init", "--quiet"], cwd=root, check=True, capture_output=True)  # nosec B603  # test harness runs a repo script with a static argv  # nosemgrep: python.lang.security.audit.dangerous-subprocess-use-audit
    if stage:
        subprocess.run(  # nosec B603  # test harness runs a repo script with a static argv  # nosemgrep: python.lang.security.audit.dangerous-subprocess-use-audit
            [GIT, "add", "--", "scripts/scan-secrets.sh", *files],
            cwd=root,
            check=True,
            capture_output=True,
        )
    else:
        subprocess.run(  # nosec B603  # test harness runs a repo script with a static argv  # nosemgrep: python.lang.security.audit.dangerous-subprocess-use-audit
            [GIT, "add", "--", "scripts/scan-secrets.sh"],
            cwd=root,
            check=True,
            capture_output=True,
        )
    return root


def run_scan(root: Path) -> subprocess.CompletedProcess:
    return subprocess.run(  # nosec B603  # test harness runs a repo script with a static argv  # nosemgrep: python.lang.security.audit.dangerous-subprocess-use-audit
        [BASH, str(root / "scripts" / "scan-secrets.sh")],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=120,
    )


def findings(result: subprocess.CompletedProcess) -> list[tuple[str, str, str]]:
    """Parse the account-identifier file:line:value lines out of stdout."""
    return [f for f in all_findings(result) if f[2].isdigit()]


def all_findings(result: subprocess.CompletedProcess) -> list[tuple[str, str, str]]:
    """Parse every file:line:value line, whatever match class produced it."""
    parsed = []
    for line in result.stdout.splitlines():
        parts = line.split(":")
        if len(parts) == 3 and parts[1].isdigit():
            parsed.append((parts[0], parts[1], parts[2]))
    return parsed


@pytest.fixture
def git_repo(tmp_path: Path):
    counter = {"n": 0}

    def _make(files: dict[str, str], stage: bool = True) -> Path:
        counter["n"] += 1
        return make_git_repo(tmp_path / f"case{counter['n']}", files, stage=stage)

    return _make


class TestNonPlaceholderIdentifiers:
    """Requirement 6.5 — a real identifier fails, naming file and line."""

    def test_non_allowlisted_id_fails_with_file_line_value(self, git_repo) -> None:
        leaked = fake_account_id(424242)
        root = git_repo(
            {
                "workload/lib/stack.ts": (
                    "const other = 'nothing here';\n"
                    f"const account = '{leaked}';\n"
                ),
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [("workload/lib/stack.ts", "2", leaked)]

    def test_every_finding_is_reported_not_just_the_first(self, git_repo) -> None:
        first, second = fake_account_id(424242), fake_account_id(777777)
        root = git_repo(
            {
                "a.md": f"account {first}\n",
                "b.md": f"line one\naccount {second}\n",
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [
            ("a.md", "1", first),
            ("b.md", "2", second),
        ]

    def test_untracked_file_is_out_of_scope(self, git_repo) -> None:
        """Scope is structural: an unstaged file is not scanned at all."""
        root = git_repo(
            {"config/accounts.json": f'{{"id": "{fake_account_id(424242)}"}}\n'},
            stage=False,
        )

        result = run_scan(root)

        assert result.returncode == 0, result.stdout + result.stderr
        assert findings(result) == []


