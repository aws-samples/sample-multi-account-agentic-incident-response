class TestStructuralScope:
    """Scope comes from ``git ls-files``, not from a pattern list."""

    def test_untracked_task_metadata_is_out_of_scope(self, git_repo) -> None:
        """Kiro spec metadata is ignored, so its epoch timestamps never reach the scan.

        An epoch-millisecond timestamp is shape-identical to an account ID, so
        the pattern does match it; structural scope, not an exclusion, is what
        keeps the scan quiet, which the paired assertion below makes explicit.
        """
        epoch_ms = str(1784219570 * 1000)  # built at runtime: 13 digits
        root = git_repo(
            {
                ".kiro/specs/centralized-parameters/tasks.meta.json": (
                    '{"updatedAt": ' + epoch_ms + "}\n"
                ),
            },
            stage=False,
        )

        result = run_scan(root)

        assert result.returncode == 0, result.stdout + result.stderr
        assert findings(result) == []

    def test_same_epoch_timestamp_in_a_tracked_file_does_trigger(
        self, git_repo
    ) -> None:
        """No path is exempt by shape: a tracked 13-digit run is reported."""
        epoch_ms = str(1784219570 * 1000)  # built at runtime: 13 digits
        root = git_repo({"notes/timing.json": '{"updatedAt": ' + epoch_ms + "}\n"})

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [("notes/timing.json", "1", epoch_ms[:12])]

    def test_tracked_task_metadata_is_still_scanned(self, git_repo) -> None:
        """The name carries no exemption — staged, the same file is in scope."""
        leaked = fake_account_id(424242)
        root = git_repo({"tasks.meta.json": f'{{"account": "{leaked}"}}\n'})

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [("tasks.meta.json", "1", leaked)]


class TestNonAccountTokens:
    """Requirement 6.6 — a masked token is skipped without excluding the file.

    The live case is the synth-time PrivateLink placeholder in
    ``workload/frontend/lib/frontend-stack.ts``: an all-zero vpce-svc- suffix
    whose leading twelve digits match the account-ID pattern. The mask is
    token-scoped rather than path-scoped precisely so that production source
    keeps being scanned, which the paired assertion below pins down.
    """

    FRONTEND_STACK = "workload/frontend/lib/frontend-stack.ts"

    def _placeholder_line(self) -> str:
        # 17-character all-zero suffix, assembled at runtime.
        return (
            "      privatelinkServiceName = "
            f"'com.amazonaws.vpce.placeholder.vpce-svc-{'0' * 17}';\n"
        )

    def test_vpce_service_placeholder_passes(self, git_repo) -> None:
        root = git_repo({self.FRONTEND_STACK: self._placeholder_line()})

        result = run_scan(root)

        assert result.returncode == 0, result.stdout + result.stderr
        assert findings(result) == []

    def test_real_id_in_the_same_file_still_fails(self, git_repo) -> None:
        """The mask is not a file exclusion: the rest of the file stays in scope."""
        leaked = fake_account_id(424242)
        root = git_repo(
            {
                self.FRONTEND_STACK: (
                    self._placeholder_line() + f"      const account = '{leaked}';\n"
                ),
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [(self.FRONTEND_STACK, "2", leaked)]

    def test_masking_does_not_shift_reported_line_numbers(self, git_repo) -> None:
        leaked = fake_account_id(777777)
        root = git_repo(
            {
                self.FRONTEND_STACK: (
                    "// header\n"
                    + self._placeholder_line()
                    + "// spacer\n"
                    + f"const account = '{leaked}';\n"
                ),
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [(self.FRONTEND_STACK, "4", leaked)]


