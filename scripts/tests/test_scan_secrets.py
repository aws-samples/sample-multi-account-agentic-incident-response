class TestBaseline:
    """Requirement 6.6 — the baseline mechanism, scoped to path and value.

    ``docs/deployment.md`` used to be a whole-file exclusion (decision D3),
    which put the scan's blind spot in the largest and fastest-growing file in
    the repository. D3 was narrowed to per-value baseline entries and has since
    been **reversed on security-standards grounds**: the run log's identifiers
    were replaced with placeholders and the shipped
    ``scripts/scan-secrets.baseline`` is empty, so nothing in the repository is
    exempt. These cases therefore exercise the mechanism against fixture
    baselines only — the shipped one accepts nothing, which
    ``test_shipped_baseline_has_no_entries`` pins down.
    """

    RUN_LOG = "docs/deployment.md"

    def test_shipped_baseline_has_no_entries(self) -> None:
        """D3 reversed: the repository's own baseline accepts nothing."""
        shipped = REPO_ROOT / "scripts" / "scan-secrets.baseline"
        entries = [
            line
            for line in shipped.read_text().splitlines()
            if line.strip() and not line.lstrip().startswith("#")
        ]

        assert entries == [], (
            "scripts/scan-secrets.baseline is intentionally empty — no file or "
            f"value in this repository is exempt from the gate: {entries}"
        )

    def test_run_log_id_without_a_baseline_entry_fails(self, git_repo) -> None:
        """No path is exempt by name: the run log is scanned like anything else."""
        historical = fake_account_id(424242)
        root = git_repo({self.RUN_LOG: f"Deployed to {historical}\n"})

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [(self.RUN_LOG, "1", historical)]

    def test_baselined_id_passes_without_editing_the_file(self, git_repo) -> None:
        historical = fake_account_id(424242)
        root = git_repo(
            {
                self.RUN_LOG: f"Deployed to {historical}\n",
                BASELINE_NAME: baseline((self.RUN_LOG, historical)),
            }
        )

        result = run_scan(root)

        assert result.returncode == 0, result.stdout + result.stderr
        assert all_findings(result) == []

    def test_new_id_in_a_baselined_file_still_fails(self, git_repo) -> None:
        """The point of the change: acceptance is per value, not per file."""
        historical, added = fake_account_id(424242), fake_account_id(777777)
        root = git_repo(
            {
                self.RUN_LOG: f"Deployed to {historical}\nLater: {added}\n",
                BASELINE_NAME: baseline((self.RUN_LOG, historical)),
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [(self.RUN_LOG, "2", added)]

    def test_acceptance_does_not_leak_into_another_path(self, git_repo) -> None:
        """A value accepted in the run log is still a leak in source."""
        historical = fake_account_id(424242)
        root = git_repo(
            {
                self.RUN_LOG: f"Deployed to {historical}\n",
                "workload/lib/stack.ts": f"const account = '{historical}';\n",
                BASELINE_NAME: baseline((self.RUN_LOG, historical)),
            }
        )

        result = run_scan(root)

        assert result.returncode != 0
        assert findings(result) == [("workload/lib/stack.ts", "1", historical)]

    def test_malformed_baseline_line_is_an_environment_error(self, git_repo) -> None:
        """A baseline that cannot be parsed must not silently accept nothing."""
        root = git_repo(
            {
                self.RUN_LOG: f"Deployed to {fake_account_id(424242)}\n",
                BASELINE_NAME: "docs/deployment.md | not-a-digest | why\n",
            }
        )

        result = run_scan(root)

        assert result.returncode == 2
        assert "sha256" in result.stderr

    def test_baseline_digests_do_not_fail_the_scan(self, git_repo) -> None:
        """A sha256 digest carries a 12-digit run often enough to matter.

        Roughly one digest in five contains twelve consecutive digits, so an
        unmasked baseline would fail the gate it feeds. The digest token is
        masked; the seeds below are chosen so at least one entry hits the case.
        """
        entries = [(self.RUN_LOG, fake_account_id(seed)) for seed in range(1, 40)]
        digests = [hashlib.sha256(v.encode()).hexdigest() for _, v in entries]
        assert any(
            any(d[i : i + 12].isdigit() for i in range(len(d) - 11)) for d in digests
        ), "fixture no longer exercises the digit-run case"

        root = git_repo(
            {
                self.RUN_LOG: "".join(f"account {v}\n" for _, v in entries),
                BASELINE_NAME: baseline(*entries),
            }
        )

        result = run_scan(root)

        assert result.returncode == 0, result.stdout + result.stderr
        assert all_findings(result) == []


